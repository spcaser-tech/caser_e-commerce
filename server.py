class PostgresRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class PostgresCursor:
    def __init__(self, cursor):
        self.cursor = cursor

    def _row(self, row):
        if row is None:
            return None
        return PostgresRow(zip((column.name for column in self.cursor.description), row))

    def fetchone(self):
        return self._row(self.cursor.fetchone())

    def fetchall(self):
        return [self._row(row) for row in self.cursor.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())

    @property
    def lastrowid(self):
        raise RuntimeError("PostgreSQL inserts must use RETURNING id.")


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    @staticmethod
    def _query(sql: str) -> str:
        return sql.replace("?", "%s")

    def execute(self, sql, parameters=()):
        return PostgresCursor(self.connection.execute(self._query(sql), parameters))

    def executemany(self, sql, parameters):
        return PostgresCursor(self.connection.executemany(self._query(sql), parameters))

    def executescript(self, sql):
        sql = sql.replace("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        sql = sql.replace(" COLLATE NOCASE", "")
        sql = sql.replace("INSERT OR IGNORE INTO", "INSERT INTO")
        sql = sql.replace("VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?) ON CONFLICT DO NOTHING")
        for statement in sql.split(";"):
            statement = statement.strip()
            if statement:
                self.connection.execute(statement)

    def __enter__(self):
        self.connection.__enter__()
        return self

    def __exit__(self, *args):
        return self.connection.__exit__(*args)


def connect():
    if DATABASE_URL:
        if psycopg is None:
            raise RuntimeError("PostgreSQL support requires psycopg. Install it with: python -m pip install psycopg[binary]")
        return PostgresConnection(psycopg.connect(DATABASE_URL, row_factory=tuple_row))
    DATABASE.parent.mkdir(parents=True, exist_ok=True)
    database = sqlite3.connect(DATABASE, timeout=10)
    database.row_factory = sqlite3.Row
    if not DATABASE_URL:
        database.execute("PRAGMA foreign_keys = ON")
    return database


DATABASE_ERROR = psycopg.Error if DATABASE_URL and psycopg else sqlite3.Error
DATABASE_INTEGRITY_ERROR = psycopg.errors.UniqueViolation if DATABASE_URL and psycopg else sqlite3.IntegrityError


def initialize_database() -> None:
    if bool(ADMIN_EMAIL) != bool(ADMIN_PASSWORD):
        raise ValueError("Set both ADMIN_EMAIL and ADMIN_PASSWORD to bootstrap the administrator account.")
    with connect() as database:
        database.executescript(
            """
            CREATE TABLE IF NOT EXISTS products (
                id INTEGER PRIMARY KEY,
                name TEXT NOT NULL,
                category TEXT NOT NULL,
                description TEXT NOT NULL,
                price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
                badge TEXT NOT NULL DEFAULT '',
                rating TEXT NOT NULL,
                review_count INTEGER NOT NULL,
                image TEXT NOT NULL,
                stock INTEGER NOT NULL DEFAULT 50 CHECK (stock >= 0)
            );
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE COLLATE NOCASE,
                password_hash TEXT NOT NULL,
                salt TEXT NOT NULL,
                created_at TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
                phone TEXT NOT NULL DEFAULT '',
                address TEXT NOT NULL DEFAULT '',
                city TEXT NOT NULL DEFAULT '',
                postal_code TEXT NOT NULL DEFAULT ''
            );
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS orders (
                id TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id),
                total_cents INTEGER NOT NULL CHECK (total_cents >= 0),
                status TEXT NOT NULL DEFAULT 'confirmed',
                created_at TEXT NOT NULL,
                payment_method TEXT NOT NULL DEFAULT 'cash',
                delivery_name TEXT NOT NULL DEFAULT '',
                delivery_phone TEXT NOT NULL DEFAULT '',
                delivery_address TEXT NOT NULL DEFAULT '',
                delivery_city TEXT NOT NULL DEFAULT '',
                delivery_postal_code TEXT NOT NULL DEFAULT '',
                coupon_code TEXT NOT NULL DEFAULT '',
                discount_cents INTEGER NOT NULL DEFAULT 0 CHECK (discount_cents >= 0)
            );
            CREATE TABLE IF NOT EXISTS order_items (
                id INTEGER PRIMARY KEY,
                order_id TEXT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
                product_id INTEGER NOT NULL REFERENCES products(id),
                name TEXT NOT NULL,
                price_cents INTEGER NOT NULL,
                quantity INTEGER NOT NULL CHECK (quantity > 0)
            );
            CREATE TABLE IF NOT EXISTS payment_transactions (
                id INTEGER PRIMARY KEY,
                order_id TEXT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
                method TEXT NOT NULL CHECK (method IN ('gcash', 'maya', 'cash', 'card')),
                status TEXT NOT NULL DEFAULT 'pending',
                masked_reference TEXT NOT NULL DEFAULT '',
                created_at TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS coupon_redemptions (
                id INTEGER PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                order_id TEXT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
                coupon_code TEXT NOT NULL,
                discount_cents INTEGER NOT NULL CHECK (discount_cents >= 0),
                redeemed_at TEXT NOT NULL,
                UNIQUE(user_id, coupon_code)
            );
            CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
            CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
            """
        )
        if DATABASE_URL:
            columns = {
                row["column_name"] for row in database.execute(
                    """SELECT column_name FROM information_schema.columns
                       WHERE table_name = 'users'"""
                )
            }
        else:
            columns = {row["name"] for row in database.execute("PRAGMA table_info(users)")}
        if "role" not in columns:
            database.execute("ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'customer'")
        for column in ("phone", "address", "city", "postal_code"):
            if column not in columns:
                database.execute(f"ALTER TABLE users ADD COLUMN {column} TEXT NOT NULL DEFAULT ''")
        if DATABASE_URL:
            order_columns = {
                row["column_name"] for row in database.execute(
                    """SELECT column_name FROM information_schema.columns
                       WHERE table_name = 'orders'"""
                )
            }
        else:
            order_columns = {row["name"] for row in database.execute("PRAGMA table_info(orders)")}
        for column in ("payment_method", "delivery_name", "delivery_phone", "delivery_address", "delivery_city", "delivery_postal_code", "coupon_code", "discount_cents"):
            if column not in order_columns:
                column_type = "INTEGER NOT NULL DEFAULT 0" if column == "discount_cents" else "TEXT NOT NULL DEFAULT ''"
                database.execute(f"ALTER TABLE orders ADD COLUMN {column} {column_type}")
        database.executemany(
            """INSERT INTO products
               (id, name, category, description, price_cents, badge, rating, review_count, image)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
               ON CONFLICT DO NOTHING""",
            [
                (
                    product["id"],
                    product["name"],
                    product["category"],
                    product["description"],
                    product["price_cents"],
                    product["badge"],
                    product["rating"],
                    product["review_count"],
                    product["image"],
                )
                for product in PRODUCT_CATALOG
            ],
        )
        if ADMIN_EMAIL and ADMIN_PASSWORD:
            if len(ADMIN_PASSWORD) < 12:
                raise ValueError("ADMIN_PASSWORD must be at least 12 characters.")
            salt = secrets.token_bytes(16)
            password_hash = hashlib.pbkdf2_hmac("sha256", ADMIN_PASSWORD.encode("utf-8"), salt, 310_000)
            database.execute(
                """INSERT INTO users (name, email, password_hash, salt, created_at, role)
                   VALUES (?, ?, ?, ?, ?, 'admin')
                   ON CONFLICT(email) DO UPDATE SET
                     name = excluded.name, password_hash = excluded.password_hash,
                     salt = excluded.salt, role = 'admin'""",
                (ADMIN_NAME, ADMIN_EMAIL, password_hash.hex(), salt.hex(), now_utc().isoformat()),
            )


def now_utc() -> datetime:
    return datetime.now(timezone.utc)


def public_user(user: sqlite3.Row) -> dict[str, object]:
    return {
        "id": user["id"], "name": user["name"], "email": user["email"],
        "role": user["role"],
        "phone": user["phone"], "address": user["address"],
        "city": user["city"], "postal_code": user["postal_code"],
    }


PAYMENT_METHODS = {"gcash", "maya", "cash", "card"}


class StoreHandler(SimpleHTTPRequestHandler):
    server_version = "GamersOasis/1.0"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def log_message(self, format: str, *args) -> None:
        print(f"{self.address_string()} - {format % args}")

    def send_json(self, status: int, data: dict[str, object]) -> None:
        payload = json.dumps(data).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(payload)

    def read_json(self) -> dict[str, object]:
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if length <= 0 or length > 16_384:
                raise ValueError
            payload = json.loads(self.rfile.read(length))
            if not isinstance(payload, dict):
                raise ValueError
            return payload
        except (ValueError, json.JSONDecodeError, UnicodeDecodeError):
            raise ValueError("Send a valid JSON object.") from None

    def authenticated_user(self) -> sqlite3.Row | None:
        header = self.headers.get("Authorization", "")
        if not header.startswith("Bearer "):
            return None
        digest = hashlib.sha256(header[7:].encode("utf-8")).hexdigest()
        with connect() as database:
            return database.execute(
                """SELECT users.* FROM sessions
                   JOIN users ON users.id = sessions.user_id
                   WHERE sessions.token_hash = ? AND sessions.expires_at > ?""",
                (digest, now_utc().isoformat()),
            ).fetchone()

    def authenticated_admin(self) -> sqlite3.Row | None:
        user = self.authenticated_user()
        return user if user is not None and user["role"] == "admin" else None

    def create_session(self, user_id: int) -> str:
        token = secrets.token_urlsafe(32)
        digest = hashlib.sha256(token.encode("utf-8")).hexdigest()
        expires = (now_utc() + timedelta(days=SESSION_DAYS)).isoformat()
        with connect() as database:
            database.execute(
                "INSERT INTO sessions (token_hash, user_id, expires_at) VALUES (?, ?, ?)",
                (digest, user_id, expires),
            )
        return token

    def do_GET(self) -> None:
        route = urlparse(self.path).path
        if route == "/api/products":
            with connect() as database:
                products = [dict(row) for row in database.execute(
                    """SELECT id, name, category, description, price_cents, badge,
                              rating, review_count, image, stock FROM products
                       WHERE stock > 0 ORDER BY id"""
                )]
            self.send_json(200, {"products": products})
        elif route == "/api/me":
            user = self.authenticated_user()
            if user is None:
                self.send_json(401, {"error": "Your session has expired. Please log in again."})
            else:
                self.send_json(200, {"user": public_user(user)})
        elif route == "/api/profile":
            user = self.authenticated_user()
            if user is None:
                self.send_json(401, {"error": "Your session has expired. Please log in again."})
            else:
                self.send_json(200, {"user": public_user(user)})
        elif route == "/api/orders":
            user = self.authenticated_user()
            if user is None:
                self.send_json(401, {"error": "Your session has expired. Please log in again."})
            else:
                with connect() as database:
                    orders = [dict(row) for row in database.execute(
                        """SELECT id, total_cents, status, created_at, payment_method,
                                  coupon_code, discount_cents, delivery_city, delivery_postal_code,
                                  payment_transactions.status AS payment_status
                           FROM orders LEFT JOIN payment_transactions
                             ON payment_transactions.order_id = orders.id
                           WHERE user_id = ?
                           ORDER BY created_at DESC LIMIT 20""",
                        (user["id"],),
                    )]
                self.send_json(200, {"orders": orders})
        elif route == "/api/coupons/welcome":
            user = self.authenticated_user()
            if user is None:
                self.send_json(401, {"error": "Your session has expired. Please log in again."})
            else:
                with connect() as database:
                    used = database.execute(
                        "SELECT 1 FROM coupon_redemptions WHERE user_id = ? AND coupon_code = 'WELCOME10'",
                        (user["id"],),
                    ).fetchone()
                self.send_json(200, {
                    "available": used is None,
                    "code": "WELCOME10",
                    "discount_percent": 10,
                })
        elif route == "/api/admin/summary":
            self.admin_summary()
        elif route.startswith("/api/"):
            self.send_json(404, {"error": "That API route does not exist."})
        else:
            asset = STATIC_FILES.get(route)
            if asset is None:
                self.send_error(404, "Not found")
                return
            filename, content_type = asset
            try:
                content = (ROOT / filename).read_bytes()
            except OSError:
                self.send_error(500, "Storefront asset unavailable")
                return
            self.send_response(200)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(content)))
            self.end_headers()
            self.wfile.write(content)

    def do_POST(self) -> None:
        route = urlparse(self.path).path
        try:
            if route == "/api/auth/register":
                self.register()
            elif route == "/api/auth/login":
                self.login()
            elif route == "/api/auth/logout":
                self.logout()
            elif route == "/api/orders":
                self.create_order()
            elif route == "/api/profile":
                self.update_profile()
            else:
                self.send_json(404, {"error": "That API route does not exist."})
        except ValueError as issue:
            self.send_json(400, {"error": str(issue)})
        except DATABASE_INTEGRITY_ERROR:
            self.send_json(409, {"error": "That email address is already registered. Try logging in instead."})
        except DATABASE_ERROR:
            self.send_json(500, {"error": "The database could not complete that request. Please try again."})

    def register(self) -> None:
        payload = self.read_json()
        name = payload.get("name")
        email = payload.get("email")
        password = payload.get("password")
        if not isinstance(name, str) or not 2 <= len(name.strip()) <= 80:
            raise ValueError("Add your name (2–80 characters).")
        if not isinstance(email, str) or len(email) > 254 or not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
            raise ValueError("Enter a valid email address.")
        if not isinstance(password, str) or len(password) < 8 or len(password) > 256:
            raise ValueError("Your password must be between 8 and 256 characters.")
        salt = secrets.token_bytes(16)
        password_hash = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 310_000)
        with connect() as database:
            cursor = database.execute(
                """INSERT INTO users (name, email, password_hash, salt, created_at)
                   VALUES (?, ?, ?, ?, ?) RETURNING id""",
                (name.strip(), email.strip().lower(), password_hash.hex(), salt.hex(), now_utc().isoformat()),
            )
            user_id = cursor.fetchone()["id"]
            user = database.execute("SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
        token = self.create_session(user_id)
        self.send_json(201, {"user": public_user(user), "token": token})

    def login(self) -> None:
        payload = self.read_json()
        email = payload.get("email")
        password = payload.get("password")
        if not isinstance(email, str) or not isinstance(password, str):
            raise ValueError("Enter your email and password.")
        with connect() as database:
            user = database.execute("SELECT * FROM users WHERE email = ?", (email.strip().lower(),)).fetchone()
        if user is None:
            self.send_json(401, {"error": "That email and password combination doesn't match."})
            return
        salt = bytes.fromhex(user["salt"])
        password_hash = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 310_000)
        if not hmac.compare_digest(password_hash.hex(), user["password_hash"]):
            self.send_json(401, {"error": "That email and password combination doesn't match."})
            return
        token = self.create_session(user["id"])
        self.send_json(200, {"user": public_user(user), "token": token})

    def logout(self) -> None:
        header = self.headers.get("Authorization", "")
        if header.startswith("Bearer "):
            digest = hashlib.sha256(header[7:].encode("utf-8")).hexdigest()
            with connect() as database:
                database.execute("DELETE FROM sessions WHERE token_hash = ?", (digest,))
        self.send_json(200, {"ok": True})

    def update_profile(self) -> None:
        user = self.authenticated_user()
        if user is None:
            self.send_json(401, {"error": "Your session has expired. Please log in again."})
            return
        payload = self.read_json()
        values = {field: payload.get(field, "") for field in ("name", "phone", "address", "city", "postal_code")}
        if not isinstance(values["name"], str) or not 2 <= len(values["name"].strip()) <= 80:
            raise ValueError("Add your name (2–80 characters).")
        for field in ("phone", "address", "city", "postal_code"):
            if not isinstance(values[field], str) or len(values[field].strip()) > 160:
                raise ValueError("Delivery information is too long.")
        with connect() as database:
            database.execute(
                """UPDATE users SET name = ?, phone = ?, address = ?, city = ?, postal_code = ?
                   WHERE id = ?""",
                tuple(values[field].strip() for field in ("name", "phone", "address", "city", "postal_code")) + (user["id"],),
            )
            updated = database.execute("SELECT * FROM users WHERE id = ?", (user["id"],)).fetchone()
        self.send_json(200, {"user": public_user(updated)})

    def admin_summary(self) -> None:
        admin = self.authenticated_admin()
        if admin is None:
            self.send_json(403, {"error": "Administrator access is required."})
            return
        with connect() as database:
            summary = {
                "users": database.execute("SELECT COUNT(*) FROM users WHERE role = 'customer'").fetchone()[0],
                "orders": database.execute("SELECT COUNT(*) FROM orders").fetchone()[0],
                "revenue_cents": database.execute("SELECT COALESCE(SUM(total_cents), 0) FROM orders").fetchone()[0],
                "low_stock": database.execute("SELECT COUNT(*) FROM products WHERE stock <= 5").fetchone()[0],
            }
            orders = [
                dict(row) for row in database.execute(
                    """SELECT orders.id, orders.total_cents, orders.status, orders.created_at,
                              orders.coupon_code, orders.discount_cents,
                              orders.payment_method, orders.coupon_code, orders.discount_cents,
                              orders.delivery_name, orders.delivery_phone,
                              orders.delivery_address, orders.delivery_city, orders.delivery_postal_code,
                              users.name AS customer_name, payment_transactions.status AS payment_status,
                              payment_transactions.masked_reference,
                              (SELECT COALESCE(SUM(quantity), 0) FROM order_items WHERE order_id = orders.id) AS item_count
                       FROM orders JOIN users ON users.id = orders.user_id
                       LEFT JOIN payment_transactions ON payment_transactions.order_id = orders.id
                       ORDER BY orders.created_at DESC LIMIT 20"""
                )
            ]
            customers = [
                dict(row) for row in database.execute(
                    """SELECT id, name, email, phone, address, city, postal_code, created_at
                       FROM users WHERE role = 'customer' ORDER BY created_at DESC LIMIT 100"""
                )
            ]
            low_stock = [
                dict(row) for row in database.execute(
                    "SELECT id, name, stock FROM products WHERE stock <= 5 ORDER BY stock, name LIMIT 20"
                )
            ]
        self.send_json(200, {"summary": summary, "orders": orders, "customers": customers, "low_stock": low_stock})

    def create_order(self) -> None:
        user = self.authenticated_user()
        if user is None:
            self.send_json(401, {"error": "Log in to your account before placing an order."})
            return
        payload = self.read_json()
        items = payload.get("items")
        payment_method = payload.get("payment_method")
        coupon_code = payload.get("coupon_code", "")
        delivery = payload.get("delivery")
        payment_details = payload.get("payment_details")
        if payment_method not in PAYMENT_METHODS:
            raise ValueError("Choose a valid payment method.")
        if not isinstance(coupon_code, str):
            raise ValueError("Enter a valid coupon code.")
        coupon_code = coupon_code.strip().upper()
        if coupon_code and coupon_code != "WELCOME10":
            raise ValueError("That coupon code is not valid.")
        if not isinstance(delivery, dict):
            raise ValueError("Add your delivery information before checking out.")
        delivery_fields = ("name", "phone", "address", "city", "postal_code")
        if any(not isinstance(delivery.get(field), str) or not delivery[field].strip() for field in delivery_fields):
            raise ValueError("Complete all delivery information before checking out.")
        if not isinstance(payment_details, dict):
            raise ValueError("Complete your payment information before checking out.")
        if payment_method in {"gcash", "maya"}:
            account = payment_details.get("account")
            if not isinstance(account, str) or not re.fullmatch(r"09\d{9}", account.strip()):
                raise ValueError("Enter a valid 11-digit mobile number for your payment account.")
        elif payment_method == "card":
            card_number = re.sub(r"\s+", "", str(payment_details.get("card_number", "")))
            expiry = str(payment_details.get("card_expiry", "")).strip()
            cvv = str(payment_details.get("card_cvv", "")).strip()
            if not re.fullmatch(r"\d{13,19}", card_number):
                raise ValueError("Enter a valid card number.")
            if not re.fullmatch(r"(0[1-9]|1[0-2])\/\d{2}", expiry):
                raise ValueError("Enter the card expiry as MM/YY.")
            if not re.fullmatch(r"\d{3,4}", cvv):
                raise ValueError("Enter a valid card security code.")
        if payment_method in {"gcash", "maya"}:
            masked_reference = f"•••• {str(payment_details['account']).strip()[-4:]}"
        elif payment_method == "card":
            masked_reference = f"•••• {card_number[-4:]}"
        else:
            masked_reference = "Pay on delivery"
        if not isinstance(items, list) or not items or len(items) > 50:
            raise ValueError("Your bag is empty. Add some gear before checking out.")
        quantities: dict[int, int] = {}
        for item in items:
            if not isinstance(item, dict):
                raise ValueError("There is an invalid item in your bag.")
            product_id = item.get("product_id")
            quantity = item.get("quantity")
            if isinstance(product_id, bool) or not isinstance(product_id, int):
                raise ValueError("There is an invalid item in your bag.")
            if isinstance(quantity, bool) or not isinstance(quantity, int) or not 1 <= quantity <= 50:
                raise ValueError("Each item quantity must be between 1 and 50.")
            quantities[product_id] = quantities.get(product_id, 0) + quantity
        if any(quantity > 50 for quantity in quantities.values()):
            raise ValueError("You can order up to 50 of each item.")

        order_id = f"AH-{now_utc():%y%m%d}-{secrets.token_hex(3).upper()}"
        created_at = now_utc().isoformat()
        with connect() as database:
            database.execute("BEGIN")
            order_items = []
            total_cents = 0
            for product_id, quantity in quantities.items():
                product = database.execute(
                    "SELECT id, name, price_cents, stock FROM products WHERE id = ?",
                    (product_id,),
                ).fetchone()
                if product is None or product["stock"] < quantity:
                    self.send_json(409, {"error": "An item in your bag is no longer available in that quantity. Please update your bag."})
                    return
                total_cents += product["price_cents"] * quantity
                order_items.append({**dict(product), "quantity": quantity})
            discount_cents = 0
            if coupon_code:
                redeemed = database.execute(
                    "SELECT 1 FROM coupon_redemptions WHERE user_id = ? AND coupon_code = ?",
                    (user["id"], coupon_code),
                ).fetchone()
                if redeemed:
                    raise ValueError("WELCOME10 can only be used on your first order.")
                discount_cents = total_cents // 10
            total_cents -= discount_cents
            database.execute(
                """INSERT INTO orders
                   (id, user_id, total_cents, status, created_at, payment_method,
                    delivery_name, delivery_phone, delivery_address, delivery_city, delivery_postal_code,
                    coupon_code, discount_cents)
                   VALUES (?, ?, ?, 'confirmed', ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (order_id, user["id"], total_cents, created_at, payment_method,
                 *(delivery[field].strip() for field in delivery_fields),
                 coupon_code, discount_cents),
            )
            if coupon_code:
                database.execute(
                    """INSERT INTO coupon_redemptions
                       (user_id, order_id, coupon_code, discount_cents, redeemed_at)
                       VALUES (?, ?, ?, ?, ?)""",
                    (user["id"], order_id, coupon_code, discount_cents, created_at),
                )
            database.execute(
                """INSERT INTO payment_transactions
                   (order_id, method, status, masked_reference, created_at)
                   VALUES (?, ?, 'pending', ?, ?)""",
                (order_id, payment_method, masked_reference, created_at),
            )
            for item in order_items:
                database.execute(
                    "INSERT INTO order_items (order_id, product_id, name, price_cents, quantity) VALUES (?, ?, ?, ?, ?)",
                    (order_id, item["id"], item["name"], item["price_cents"], item["quantity"]),
                )
                database.execute(
                    "UPDATE products SET stock = stock - ? WHERE id = ?",
                    (item["quantity"], item["id"]),
                )
        self.send_json(201, {
            "id": order_id,
            "total_cents": total_cents,
            "status": "confirmed",
            "payment_method": payment_method,
            "coupon_code": coupon_code,
            "discount_cents": discount_cents,
            "created_at": created_at,
            "items": [
                {"product_id": item["id"], "name": item["name"], "price_cents": item["price_cents"], "quantity": item["quantity"]}
                for item in order_items
            ],
        })

